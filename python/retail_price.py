# ============================================================
# 3. OUTLIER DETECTION (IQR method)
# ============================================================

def detect_outliers_iqr(df,col):
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1
    lower = Q1 - 1.5 * IQR
    upper = Q3 + 1.5 * IQR
    outliers = df[(df[col] < lower) | (df[col] > upper)]
    return outliers , lower , upper

for col in ['unit_price', 'total_price', 'freight_price' , 'qty']:
  out,lo,hi = detect_outliers_iqr(df,col)
  print(f"{col}: {len(out)} outliers | range [{lo:.2f},{hi:.2f}]")

"""**Outlier Analysis Insights**

1.Outlier analysis using the IQR method identified significant variability in unit price, total revenue, freight cost, and sales quantity.

2.High unit price outliers represented premium-priced products and distinct pricing segments within the dataset.

3.Revenue outliers indicated a small number of products contributing disproportionately to total sales.

4.Freight price showed the highest number of outliers, suggesting substantial differences in logistics and shipping costs across products.

5.Quantity outliers reflected exceptionally high-demand products and potential promotional or seasonal sales spikes.

6.Outliers were retained during modeling because they reflected meaningful business patterns rather than data-quality errors.
"""

