# ============================================================
# 9. PRICE ELASTICITY ANALYSIS
# ============================================================
df_elast = df[df['lag_price'] > 0].copy()
df_elast['price_change_pct'] = (df_elast['unit_price'] - df_elast['lag_price']) / df_elast['lag_price']
df_elast['qty_change'] = df_elast.groupby('product_id')['qty'].pct_change()
df_elast.dropna(subset=['qty_change'], inplace=True)

df_elast['elasticity'] = df_elast['qty_change'] / df_elast['price_change_pct'].replace(0, np.nan)
df_elast['elasticity'].clip(-10, 10, inplace=True)

print("Average Price Elasticity:", df_elast['elasticity'].mean())
print(df_elast.groupby('product_category_name')['elasticity'].mean().sort_values())

