# 8. COMPETITOR PRICE ANALYSIS
# ============================================================
df['avg_comp_price'] = (df['comp_1'] + df['comp_2'] + df['comp_3']) / 3
df['price_vs_comp']  = df['unit_price'] - df['avg_comp_price']
